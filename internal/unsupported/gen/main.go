// Command gen writes unsupported.go: for each service interface of the root
// package, a struct whose methods all answer ErrNotSupported. Run it with
// go generate in internal/unsupported after changing an interface.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

func main() {
	root := filepath.Join("..", "..")
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, root, func(fi os.FileInfo) bool { return !strings.HasSuffix(fi.Name(), "_test.go") }, 0)
	check(err)
	pkg := pkgs["gitoperationslib"]
	ifaces := map[string]*ast.InterfaceType{}
	kinds := map[string]string{} // exported type name → "interface", "struct", "other"
	for _, f := range pkg.Files {
		for _, d := range f.Decls {
			g, ok := d.(*ast.GenDecl)
			if !ok || g.Tok != token.TYPE {
				continue
			}
			for _, s := range g.Specs {
				ts := s.(*ast.TypeSpec)
				switch t := ts.Type.(type) {
				case *ast.InterfaceType:
					kinds[ts.Name.Name] = "interface"
					if ts.Name.Name != "Client" {
						ifaces[ts.Name.Name] = t
					}
				case *ast.StructType:
					kinds[ts.Name.Name] = "struct"
				default:
					kinds[ts.Name.Name] = "other"
				}
			}
		}
	}
	var names []string
	for n := range ifaces {
		names = append(names, n)
	}
	sort.Strings(names)

	var buf bytes.Buffer
	buf.WriteString(`// Code generated by gen; DO NOT EDIT.

// Package unsupported answers ErrNotSupported for every method of the root
// package's services. A backend returns one of these for a service it lacks,
// or embeds one in its own service and implements only what it can.
package unsupported

import (
	"context"
	"io"

	gol "github.com/jeanfrancoisgratton/gitoperationslib"
)

var (
	_ context.Context
	_ io.Reader
)
`)
	for _, n := range names {
		area := snake(n)
		fmt.Fprintf(&buf, "\n// %s answers ErrNotSupported for every gol.%s method, giving Reason.\ntype %s struct {\n\tBackend gol.Backend\n\tReason  string\n}\n\nvar _ gol.%s = %s{}\n", n, n, n, n, n)
		for _, m := range ifaces[n].Methods.List {
			ft, ok := m.Type.(*ast.FuncType)
			if !ok || len(m.Names) == 0 {
				continue
			}
			name := m.Names[0].Name
			qualify(ft, kinds)
			op := area + "." + snake(name)
			var results []string
			var sub string
			if ft.Results != nil {
				for _, r := range ft.Results.List {
					count := max(1, len(r.Names))
					for range count {
						results = append(results, zero(r.Type, kinds))
					}
				}
				if len(ft.Results.List) == 1 && len(ft.Params.List) <= 1 {
					if se, ok := ft.Results.List[0].Type.(*ast.SelectorExpr); ok && ifaces[se.Sel.Name] != nil {
						sub = se.Sel.Name // an accessor: the unsupported service
					}
				}
			}
			sig := render(fset, ft)
			fmt.Fprintf(&buf, "\nfunc (u %s) %s%s {\n", n, name, strings.TrimPrefix(sig, "func"))
			switch {
			case sub != "":
				fmt.Fprintf(&buf, "\treturn %s{Backend: u.Backend, Reason: u.Reason}\n", sub)
			default:
				for i, r := range results {
					if r == "error" {
						results[i] = fmt.Sprintf("gol.NotSupported(u.Backend, %q, u.Reason)", op)
					}
				}
				fmt.Fprintf(&buf, "\treturn %s\n", strings.Join(results, ", "))
			}
			buf.WriteString("}\n")
		}
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		os.WriteFile("unsupported.go", buf.Bytes(), 0o644)
		check(err)
	}
	check(os.WriteFile("unsupported.go", out, 0o644))
}

// qualify prefixes the root package's exported types with gol., and names
// unnamed parameters.
func qualify(ft *ast.FuncType, kinds map[string]string) {
	ast.Inspect(ft, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.SelectorExpr:
			return false
		case *ast.Field:
			n.Type = qual(n.Type, kinds)
		}
		return true
	})
	for i, p := range ft.Params.List {
		if len(p.Names) == 0 {
			p.Names = []*ast.Ident{ast.NewIdent(fmt.Sprintf("p%d", i))}
		}
		for _, id := range p.Names {
			id.Name = "_"
		}
	}
	if ft.Results != nil {
		for _, r := range ft.Results.List {
			r.Names = nil
		}
	}
}

func qual(e ast.Expr, kinds map[string]string) ast.Expr {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := kinds[t.Name]; ok && unicode.IsUpper(rune(t.Name[0])) {
			return &ast.SelectorExpr{X: ast.NewIdent("gol"), Sel: ast.NewIdent(t.Name)}
		}
	case *ast.StarExpr:
		t.X = qual(t.X, kinds)
	case *ast.ArrayType:
		t.Elt = qual(t.Elt, kinds)
	case *ast.Ellipsis:
		t.Elt = qual(t.Elt, kinds)
	case *ast.MapType:
		t.Key, t.Value = qual(t.Key, kinds), qual(t.Value, kinds)
	case *ast.IndexExpr:
		t.X, t.Index = qual(t.X, kinds), qual(t.Index, kinds)
	}
	return e
}

func zero(e ast.Expr, kinds map[string]string) string {
	switch t := e.(type) {
	case *ast.StarExpr, *ast.ArrayType, *ast.MapType, *ast.FuncType, *ast.InterfaceType:
		return "nil"
	case *ast.Ident:
		switch t.Name {
		case "error":
			return "error"
		case "bool":
			return "false"
		case "string":
			return `""`
		}
		return "0"
	case *ast.SelectorExpr:
		x := t.X.(*ast.Ident).Name
		if x != "gol" {
			return "nil" // io.Reader, io.ReadCloser…
		}
		switch kinds[t.Sel.Name] {
		case "interface":
			return "nil"
		case "struct":
			return "gol." + t.Sel.Name + "{}"
		}
		return `""` // string kinds such as gol.Visibility
	case *ast.IndexExpr:
		var b strings.Builder
		printer.Fprint(&b, token.NewFileSet(), t)
		return b.String() + "{}"
	}
	panic(fmt.Sprintf("no zero value for %T", e))
}

func render(fset *token.FileSet, ft *ast.FuncType) string {
	var b strings.Builder
	check(printer.Fprint(&b, fset, ft))
	return b.String()
}

// snake turns "RegistrationToken" into "registration_token", as the
// backends name operations; "ByID" stays one word.
func snake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if unicode.IsUpper(r) && i > 0 && !(r == 'D' && s[i-1] == 'I') {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

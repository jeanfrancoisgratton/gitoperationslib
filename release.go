package gitoperationslib

import "time"

// Release is a named, tagged point in a repository's history, with notes and
// attached files (assets).
type Release struct {
	ID              int64
	TagName         string
	TargetCommitish string // branch or commit the tag is created from
	Name            string // title
	Body            string // notes, Markdown
	Draft           bool
	Prerelease      bool
	Author          string // login
	HTMLURL         string
	TarballURL      string // source archives generated by the forge
	ZipballURL      string
	CreatedAt       time.Time
	PublishedAt     time.Time // zero for drafts
	Assets          []Asset
}

// Asset is a file attached to a release.
type Asset struct {
	ID            int64
	Name          string
	Size          int64
	ContentType   string // reported by GitHub only
	DownloadCount int64
	DownloadURL   string // browser download URL
	// External marks a Forgejo asset that links to a file hosted elsewhere
	// (DownloadURL) instead of an uploaded file.
	External  bool
	CreatedAt time.Time
}

// CreateReleaseOptions describes a release to create.
//
// If TagName does not exist yet, it is created from TargetCommitish (the
// default branch when empty). For a draft, both backends create the tag only
// when the draft is published.
type CreateReleaseOptions struct {
	TagName         string // required
	TargetCommitish string
	Name            string
	Body            string
	Draft           bool
	Prerelease      bool

	// GenerateReleaseNotes asks the server to write the notes from merged
	// pull requests (GitHub only).
	GenerateReleaseNotes bool
	// MakeLatest controls whether the release becomes the "latest" one;
	// nil means the server decides (GitHub only).
	MakeLatest *bool
	// HideArchiveLinks hides the generated source archives (Forgejo only).
	HideArchiveLinks *bool
}

// EditReleaseOptions changes a release. Nil fields are left unchanged.
// Setting Draft to false publishes a draft.
type EditReleaseOptions struct {
	TagName         *string
	TargetCommitish *string
	Name            *string
	Body            *string
	Draft           *bool
	Prerelease      *bool

	MakeLatest       *bool // GitHub only
	HideArchiveLinks *bool // Forgejo only
}

// EditAssetOptions changes an asset. Nil fields are left unchanged.
type EditAssetOptions struct {
	Name *string
}

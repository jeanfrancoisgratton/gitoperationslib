package gitoperationslib

import "time"

// Release is a named, tagged point in a repository's history, with notes and
// attached files (assets).
type Release struct {
	ID              int64     `json:"id"`
	TagName         string    `json:"tagName"`
	TargetCommitish string    `json:"targetCommitish"` // branch or commit the tag is created from
	Name            string    `json:"name"`            // title
	Body            string    `json:"body"`            // notes, Markdown
	Draft           bool      `json:"draft"`
	Prerelease      bool      `json:"prerelease"`
	Author          string    `json:"author"` // login
	HTMLURL         string    `json:"htmlUrl"`
	TarballURL      string    `json:"tarballUrl"` // source archives generated by the forge
	ZipballURL      string    `json:"zipballUrl"`
	CreatedAt       time.Time `json:"createdAt,omitzero"`
	PublishedAt     time.Time `json:"publishedAt,omitzero"` // zero for drafts
	Assets          []Asset   `json:"assets"`
}

// Asset is a file attached to a release.
type Asset struct {
	ID            int64  `json:"id"`
	Name          string `json:"name"`
	Size          int64  `json:"size"`
	ContentType   string `json:"contentType,omitzero"` // reported by GitHub only
	DownloadCount int64  `json:"downloadCount"`
	DownloadURL   string `json:"downloadUrl"` // browser download URL
	// External marks a Forgejo asset that links to a file hosted elsewhere
	// (DownloadURL) instead of an uploaded file.
	External  bool      `json:"external,omitzero"`
	CreatedAt time.Time `json:"createdAt,omitzero"`
}

// CreateReleaseOptions describes a release to create.
//
// If TagName does not exist yet, it is created from TargetCommitish (the
// default branch when empty). For a draft, both backends create the tag only
// when the draft is published.
type CreateReleaseOptions struct {
	TagName         string `json:"tagName"` // required
	TargetCommitish string `json:"targetCommitish,omitzero"`
	Name            string `json:"name,omitzero"`
	Body            string `json:"body,omitzero"`
	Draft           bool   `json:"draft,omitzero"`
	Prerelease      bool   `json:"prerelease,omitzero"`

	// GenerateReleaseNotes asks the server to write the notes from merged
	// pull requests (GitHub only).
	GenerateReleaseNotes bool `json:"generateReleaseNotes,omitzero"`
	// MakeLatest controls whether the release becomes the "latest" one;
	// nil means the server decides (GitHub only).
	MakeLatest *bool `json:"makeLatest,omitzero"`
	// HideArchiveLinks hides the generated source archives (Forgejo only).
	HideArchiveLinks *bool `json:"hideArchiveLinks,omitzero"`
}

// EditReleaseOptions changes a release. Nil fields are left unchanged.
// Setting Draft to false publishes a draft.
type EditReleaseOptions struct {
	TagName         *string `json:"tagName,omitzero"`
	TargetCommitish *string `json:"targetCommitish,omitzero"`
	Name            *string `json:"name,omitzero"`
	Body            *string `json:"body,omitzero"`
	Draft           *bool   `json:"draft,omitzero"`
	Prerelease      *bool   `json:"prerelease,omitzero"`

	MakeLatest       *bool `json:"makeLatest,omitzero"`       // GitHub only
	HideArchiveLinks *bool `json:"hideArchiveLinks,omitzero"` // Forgejo only
}

// EditAssetOptions changes an asset. Nil fields are left unchanged.
type EditAssetOptions struct {
	Name *string `json:"name,omitzero"`
}
